import { test, expect } from './fixtures'
import { montarQuiosque, criarAna } from './quiosque'

test('equipe revisa e cancela item ou pedido não pago com motivo e saldo atualizado', async ({ page, browser }) => {
  test.setTimeout(120_000)
  const q = await montarQuiosque(page, browser)
  const { dono, app } = q
  await dono.getByRole('link', { name: 'Regras', exact: true }).click()
  await dono.locator('#modo-POR_PEDIDO').check()
  await dono.getByRole('button', { name: 'Salvar regras' }).click()
  await expect(dono.getByText('Regras salvas.')).toBeVisible()
  const cliente = await criarAna(q)
  await cliente.getByRole('link', { name: 'Meus pedidos', exact: true }).click()
  await expect(cliente.getByText('Aguardando pagamento', { exact: true }).first()).toBeVisible()
  await app.getByRole('link', { name: /^Pagamentos/ }).click()
  await app.getByRole('button', { name: 'Revisar pedidos não pagos de Ana' }).click()
  const revisar = app.getByRole('dialog', { name: 'Pedidos ainda não pagos · Ana' })
  await expect(revisar.getByText('2× Água de coco · sem gelo')).toBeVisible()
  await revisar.getByRole('button', { name: 'Cancelar pedido não pago 1' }).click()
  const cancelar = app.getByRole('dialog', { name: 'Cancelar o pedido nº 1' })
  await cancelar.getByLabel('1× Pastel', { exact: true }).check()
  await cancelar.getByRole('button', { name: 'Confirmar cancelamento' }).click()
  await expect(cancelar.getByText('Escolha o motivo do cancelamento.')).toBeVisible()
  await cancelar.getByLabel('Esgotou', { exact: true }).check()
  await cancelar.getByRole('button', { name: 'Confirmar cancelamento' }).click()
  await expect(cancelar).toBeHidden()
  await expect(revisar.getByText('1× Pastel')).toHaveCount(0)
  await revisar.getByRole('button', { name: 'Voltar', exact: true }).click()
  await expect(app.locator('[data-comanda="Ana"]')).toContainText('R$ 24,00')
  await expect(cliente.getByText('Sua conta: R$ 24,00')).toBeVisible()
  await app.getByRole('button', { name: 'Revisar pedidos não pagos de Ana' }).click()
  await app.getByRole('button', { name: 'Cancelar pedido não pago 1' }).click()
  await cancelar.getByLabel('Cliente desistiu', { exact: true }).check()
  await cancelar.getByRole('button', { name: 'Confirmar cancelamento' }).click()
  await expect(revisar.getByText('Nenhum pedido aguarda pagamento nesta conta.')).toBeVisible()
  await expect(cliente.getByText('Sua conta: R$ 0,00')).toBeVisible()
})
