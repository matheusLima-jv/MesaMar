import { test, expect } from './fixtures'
import { montarQuiosque } from './quiosque'
import { pendencias, checkin } from './offline-helpers'

test('equipe preserva check-in e pedido na primeira reabertura offline, confirma em ordem e mantém QR', async ({ page, browser }) => {
  test.setTimeout(90000)
  const { app } = await montarQuiosque(page, browser)
  await app.getByRole('link', { name: 'Cardápio' }).click()
  await expect(app.getByRole('heading', { name: 'Cardápio' })).toBeVisible()
  await app.getByRole('link', { name: 'Clientes' }).click()
  await app.evaluate(async () => { await navigator.serviceWorker.ready })
  await expect.poll(() => app.evaluate(() => navigator.serviceWorker.controller !== null)).toBe(true)
  await app.context().setOffline(true)
  await checkin(app, 'Cliente sem rede')
  await expect(app.getByText('Cadastro preservado.', { exact: false })).toBeVisible()
  const salvo = (await pendencias(app))[0]
  expect(salvo.tipo).toBe('checkin'); expect(salvo.dados.token).toHaveLength(22)
  await app.getByRole('button', { name: 'Pronto' }).click()
  await app.reload()
  await expect(app.getByRole('button', { name: 'Mostrar o QR de Cliente sem rede' })).toBeVisible()
  await app.getByRole('button', { name: 'Lançar pedido para Cliente sem rede' }).click()
  await app.getByRole('button', { name: 'Mais um Pastel' }).click()
  await app.getByRole('button', { name: /Lançar pedido/ }).click()
  await expect(app.getByText('Pedido preservado neste aparelho.', { exact: false })).toBeVisible()
  const fila = await pendencias(app)
  expect(fila.map(p => p.tipo)).toEqual(['checkin', 'lancamento'])
  expect(fila[0].dados.token).toBe(salvo.dados.token)
  expect(fila[1].comandaId).toBe(salvo.id)
  await app.context().setOffline(false)
  await expect.poll(async () => (await pendencias(app)).length, { timeout: 25000 }).toBe(0)
  const clientes = await (await app.request.get('/api/staff/clientes?pagina=0')).json()
  const cliente = clientes.find((c: { id: string }) => c.id === salvo.id)
  expect(cliente.link).toContain('/c/' + salvo.dados.token)
  expect(clientes.filter((c: { id: string }) => c.id === salvo.id)).toHaveLength(1)
  const pedidos = await (await app.request.get('/api/staff/fila')).json()
  expect(pedidos.pedidos.filter((p: { id: string }) => p.id === fila[1].id)).toHaveLength(1)
  await app.getByRole('button', { name: 'Voltar', exact: true }).click()
  await app.getByRole('link', { name: 'Mais' }).click()
  await app.context().setOffline(true)
  await app.getByRole('button', { name: 'Sair deste celular' }).click()
  await expect(app.getByRole('tab', { name: 'Sou da equipe' })).toBeVisible()
  await app.reload()
  await expect(app.getByRole('tab', { name: 'Sou da equipe' })).toBeVisible()
  await app.context().setOffline(false)
})

