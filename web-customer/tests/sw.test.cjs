const { test } = require('node:test')
const assert = require('node:assert/strict')
const carregar = require('../../web-shared/tests/sw-harness.cjs')
const request = caminho => new Request('https://mesamar.com.br' + caminho)
test('primeira instalação, primeira reabertura offline e isolamento do cache da equipe', async () => {
  const h = carregar('web-customer', { fetch: async () => { throw new Error('offline') } })
  await h.evento('install'); assert.equal(h.skipped(), true)
  await (await h.caches.open('mesamar-staff-outra')).put('/staff/', new Response('equipe'))
  await h.evento('activate'); assert.equal(h.claimed(), true)
  const r = await h.evento('fetch', { request: { url: 'https://mesamar.com.br/c/token', method: 'GET', mode: 'navigate' } })
  assert.equal(await r.text(), 'shell'); assert(h.lojas.has('mesamar-staff-outra'))
})
test('atualização preserva comanda válida e remove expiradas antes da consulta offline', async () => {
  const h = carregar('web-customer', { fetch: async () => { throw new Error('offline') } })
  await h.evento('install')
  const velho = await h.caches.open('mesamar-cliente-antiga')
  await velho.put('/api/c/atual', new Response('comanda', { headers: { 'X-MesaMar-Salvo-Em': String(Date.now() - 1000) } }))
  await velho.put('/api/c/expirada', new Response('dados antigos', { headers: { 'X-MesaMar-Salvo-Em': String(Date.now() - 8 * 86400000) } }))
  await h.evento('activate')
  assert(!h.lojas.has('mesamar-cliente-antiga'))
  assert.equal(await (await h.evento('fetch', { request: request('/api/c/atual') })).text(), 'comanda')
  assert.equal((await h.evento('fetch', { request: request('/api/c/expirada') })).type, 'error')
})
test('quota na instalação mantém versão anterior sem ativar uma publicação incompleta', async () => {
  const h = carregar('web-customer', { quota: true })
  h.lojas.set('mesamar-cliente-antiga', new Map())
  await assert.rejects(h.evento('install'), /Quota/)
  assert.equal(h.skipped(), false); assert(h.lojas.has('mesamar-cliente-antiga'))
})
test('404 de comanda revogada elimina cópia e POST nunca é interceptado', async () => {
  const h = carregar('web-customer', { fetch: async () => new Response('', { status: 404 }) })
  const cache = await h.caches.open('mesamar-cliente-dev')
  await cache.put('/api/c/revogada', new Response('privado'))
  assert.equal((await h.evento('fetch', { request: request('/api/c/revogada') })).status, 404)
  assert.equal(await cache.match('/api/c/revogada'), undefined)
  assert.equal(await h.evento('fetch', { request: new Request('https://mesamar.com.br/api/c/t/pedidos', { method: 'POST' }) }), undefined)
})
